import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const inputPath = process.argv[2] ?? 'src/frontend/ETOmniverse.Web/src/api/openapi.json'
const outputPath = process.argv[3] ?? 'src/frontend/ETOmniverse.Web/src/api/generated/openapi-contract.ts'

const document = JSON.parse(readFileSync(inputPath, 'utf8').replace(/^\uFEFF/, ''))
const paths = document.paths ?? {}
const methods = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head']

const operations = []

for (const path of Object.keys(paths).sort()) {
  const pathItem = paths[path] ?? {}
  for (const method of methods) {
    if (!pathItem[method]) {
      continue
    }

    const operation = pathItem[method]
    operations.push({
      method: method.toUpperCase(),
      path,
      operationId: operation.operationId ?? `${method}_${path.replace(/[^a-zA-Z0-9]+/g, '_')}`,
      tags: operation.tags ?? [],
      summary: operation.summary ?? ''
    })
  }
}

operations.sort((left, right) => {
  const byPath = left.path.localeCompare(right.path)
  if (byPath !== 0) {
    return byPath
  }

  return left.method.localeCompare(right.method)
})

const body = `// <auto-generated />
// Generated by scripts/generate-frontend-api-contract.mjs from src/api/openapi.json.
// Do not edit by hand.

export type ApiMethod = 'DELETE' | 'GET' | 'HEAD' | 'OPTIONS' | 'PATCH' | 'POST' | 'PUT'

export interface ApiOperation {
  readonly method: ApiMethod
  readonly path: string
  readonly operationId: string
  readonly tags: readonly string[]
  readonly summary: string
}

export const openApiOperations = ${JSON.stringify(operations, null, 2)} as const satisfies readonly ApiOperation[]

export type OpenApiOperationId = typeof openApiOperations[number]['operationId']
export type OpenApiPath = typeof openApiOperations[number]['path']
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, body, 'utf8')
console.log(`Generated ${outputPath}`)
